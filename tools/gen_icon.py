"""Generates the "Parada" adaptive icon layers (108x108 viewport) for the app.

Same geometry as the option shown in the icon artifact: pole, white round stop
sign with a yellow ring, and the bus glyph scaled 0.56 around (54, 45.5).
"""
import sys

RES = sys.argv[1]
S = 0.56
CX, CY = 54.0, 45.5


def tx(x):
    return CX + (x - 54) * S


def ty(y):
    return CY + (y - 54) * S


def f(v):
    return f"{v:.3f}".rstrip("0").rstrip(".")


def rrect(x, y, w, h, r):
    """Rounded rectangle path in absolute coords."""
    return (f"M{f(x + r)},{f(y)} H{f(x + w - r)} A{f(r)},{f(r)} 0 0 1 {f(x + w)},{f(y + r)} "
            f"V{f(y + h - r)} A{f(r)},{f(r)} 0 0 1 {f(x + w - r)},{f(y + h)} "
            f"H{f(x + r)} A{f(r)},{f(r)} 0 0 1 {f(x)},{f(y + h - r)} "
            f"V{f(y + r)} A{f(r)},{f(r)} 0 0 1 {f(x + r)},{f(y)} Z")


def circle(cx, cy, r):
    return (f"M{f(cx - r)},{f(cy)} A{f(r)},{f(r)} 0 1 1 {f(cx + r)},{f(cy)} "
            f"A{f(r)},{f(r)} 0 1 1 {f(cx - r)},{f(cy)} Z")


def bus_rect(x, y, w, h, r):
    return rrect(tx(x), ty(y), w * S, h * S, r * S)


# Bus glyph parts (base coordinates from the artifact).
BODY = bus_rect(38, 33, 32, 37, 6)
WHEEL_L = bus_rect(40, 67, 6.5, 8, 2)
WHEEL_R = bus_rect(61.5, 67, 6.5, 8, 2)
# Wheels below the body only (for the even-odd cut-out in the monochrome layer).
WHEEL_L_LOW = bus_rect(40, 70, 6.5, 5, 2)
WHEEL_R_LOW = bus_rect(61.5, 70, 6.5, 5, 2)
BAND = bus_rect(43, 36.5, 22, 3.6, 1.8)
WINDSHIELD = bus_rect(41.5, 43, 25, 13.5, 2.6)
LIGHT_L = circle(tx(44.6), ty(62.6), 2.5 * S)
LIGHT_R = circle(tx(63.4), ty(62.6), 2.5 * S)

POLE = rrect(52, 58, 4, 25, 2)
SIGN = circle(54, 45, 18)
RING = circle(54, 45, 18)

NAVY = "#FF12355B"
WHITE = "#FFFFFFFF"
YELLOW = "#FFF2B705"
POLE_C = "#FF9FB3CC"


def path(d, fill=None, stroke=None, width=None, even_odd=False):
    attrs = [f'android:pathData="{d}"']
    if fill:
        attrs.append(f'android:fillColor="{fill}"')
    if stroke:
        attrs.append(f'android:strokeColor="{stroke}"')
        attrs.append(f'android:strokeWidth="{width}"')
    if even_odd:
        attrs.append('android:fillType="evenOdd"')
    return "    <path\n        " + "\n        ".join(attrs) + " />\n"


HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n'
          '<!-- Generated by tools/gen_icon.py: "Parada" icon (stop sign + bus). -->\n'
          '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
          '    android:width="108dp"\n    android:height="108dp"\n'
          '    android:viewportWidth="108"\n    android:viewportHeight="108">\n')

fg = HEADER
fg += path(POLE, fill=POLE_C)
fg += path(SIGN, fill=WHITE)
fg += path(RING, stroke=YELLOW, width="3.2")
for d in (BODY, WHEEL_L, WHEEL_R):
    fg += path(d, fill=NAVY)
for d in (BAND, WINDSHIELD, LIGHT_L, LIGHT_R):
    fg += path(d, fill=WHITE)
fg += "</vector>\n"

# Monochrome (Android 13+ themed icons): one tinted color; the bus is cut out of
# the sign, with its windows and lights drawn back in.
mono = HEADER
mono += path(POLE, fill=WHITE)
mono += path(" ".join([circle(54, 45, 19.6), BODY, WHEEL_L_LOW, WHEEL_R_LOW]), fill=WHITE, even_odd=True)
for d in (BAND, WINDSHIELD, LIGHT_L, LIGHT_R):
    mono += path(d, fill=WHITE)
mono += "</vector>\n"

open(f"{RES}/drawable/ic_launcher_foreground.xml", "w", encoding="utf-8", newline="\n").write(fg)
open(f"{RES}/drawable/ic_launcher_monochrome.xml", "w", encoding="utf-8", newline="\n").write(mono)
print("ok")
